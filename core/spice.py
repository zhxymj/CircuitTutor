# -*- coding: utf-8 -*-
"""
spice.py - SPICE netlist export (ngspice compatible, stdlib only)
================================================================
* to_cir(circuit, title) -> str
* to_subckt(circuit, name) -> str

Teaching-grade models; ICs become black-box subckt stubs.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List, Optional, Tuple


def _spice_value(s: Any, default: str = "1") -> str:
    if s is None or s == "":
        return default
    t = str(s).strip()
    t = t.replace("\u03a9", "").replace("\u6b27\u59c6", "").replace("\u6b27", "")
    t = t.replace("\u00b5", "u").replace("\u03bc", "u")
    t = t.replace("uF", "u").replace("nF", "n").replace("pF", "p").replace("mF", "m")
    t = re.sub(r"([0-9.]+)F\b", r"\1", t)
    t = t.replace(" ", "")
    return t or default


def _build_pin_net_map(circuit: dict) -> Dict[str, str]:
    pin2net: Dict[str, str] = {}
    parts = {str(p.get("id")): p for p in (circuit.get("parts") or []) if isinstance(p, dict)}
    parent = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb

    for conn in circuit.get("connections") or []:
        if not isinstance(conn, (list, tuple)) or len(conn) < 2:
            continue
        a, b = conn[0], conn[1]
        if isinstance(a, str) and isinstance(b, str) and ":" in a and ":" in b:
            union(a, b)
            find(a)
            find(b)

    # assign names
    groups = {}
    for pin in list(parent.keys()):
        groups.setdefault(find(pin), []).append(pin)
    n = 0
    for root, pins in groups.items():
        # power?
        name = None
        for pin in pins:
            pid = pin.split(":", 1)[0]
            ptype = parts.get(pid, {}).get("type")
            if ptype == "gnd":
                name = "0"
                break
            if ptype == "vcc":
                name = "VCC"
                break
        if name is None:
            n += 1
            name = f"N{n}"
        for pin in pins:
            pin2net[pin] = name
    return pin2net


def _pin(pin2net: Dict[str, str], ref: str, pin: str, default: str = None) -> str:
    return pin2net.get(f"{ref}:{pin}", default or f"N_{ref}_{pin}")


def to_cir(circuit: dict, title: str = "CircuitTutor") -> str:
    lines = [f"* {title}", "* generated by CircuitTutor SPICE export"]
    pin2net = _build_pin_net_map(circuit)
    parts = [p for p in (circuit.get("parts") or []) if isinstance(p, dict)]
    by_type = {}
    for p in parts:
        by_type.setdefault(str(p.get("type")), []).append(p)

    # voltage sources from battery / vcc
    vnum = 0
    for p in by_type.get("battery") or []:
        rid = str(p.get("id"))
        val = _spice_value((p.get("attrs") or {}).get("value"), "5")
        # strip trailing V
        val = val.rstrip("Vv") or "5"
        vnum += 1
        plus = _pin(pin2net, rid, "+", "VCC")
        minus = _pin(pin2net, rid, "-", "0")
        lines.append(f"V{vnum} {plus} {minus} DC {val}")
    if any(True for _ in by_type.get("vcc") or []) and not any(True for _ in by_type.get("battery") or []):
        vnum += 1
        # find any vcc pin
        vcc_id = str((by_type["vcc"][0]).get("id"))
        lines.append(f"V{vnum} VCC 0 DC 5")

    rnum = 0
    for p in by_type.get("resistor") or []:
        rid = str(p.get("id"))
        val = _spice_value((p.get("attrs") or {}).get("value"), "1k")
        rnum += 1
        n1 = _pin(pin2net, rid, "1")
        n2 = _pin(pin2net, rid, "2")
        lines.append(f"R{rnum} {n1} {n2} {val}")

    cnum = 0
    for p in (by_type.get("capacitor") or []) + (by_type.get("electrolytic") or []) + \
             (by_type.get("capacitor_ceramic") or []) + (by_type.get("capacitor_film") or []) + \
             (by_type.get("capacitor_tantalum") or []):
        rid = str(p.get("id"))
        val = _spice_value((p.get("attrs") or {}).get("value"), "100n")
        cnum += 1
        n1 = _pin(pin2net, rid, "+", _pin(pin2net, rid, "1"))
        n2 = _pin(pin2net, rid, "-", _pin(pin2net, rid, "2"))
        lines.append(f"C{cnum} {n1} {n2} {val}")

    lnum = 0
    for p in (by_type.get("inductor") or []) + (by_type.get("ferrite_bead") or []):
        rid = str(p.get("id"))
        val = _spice_value((p.get("attrs") or {}).get("value"), "1u")
        lnum += 1
        n1 = _pin(pin2net, rid, "1")
        n2 = _pin(pin2net, rid, "2")
        lines.append(f"L{lnum} {n1} {n2} {val}")

    dnum = 0
    for p in (by_type.get("diode") or []) + (by_type.get("zener") or []) + \
             (by_type.get("schottky") or []) + (by_type.get("diode_rectifier") or []) + \
             (by_type.get("tvs") or []):
        rid = str(p.get("id"))
        dnum += 1
        a = _pin(pin2net, rid, "A", _pin(pin2net, rid, "+"))
        k = _pin(pin2net, rid, "K", _pin(pin2net, rid, "-"))
        lines.append(f"D{dnum} {a} {k} DMOD")

    ledn = 0
    for p in (by_type.get("led") or []) + (by_type.get("led_rgb") or []):
        rid = str(p.get("id"))
        ledn += 1
        a = _pin(pin2net, rid, "+", _pin(pin2net, rid, "R", _pin(pin2net, rid, "A")))
        k = _pin(pin2net, rid, "-", _pin(pin2net, rid, "K"))
        lines.append(f"DLED{ledn} {a} {k} LEDMOD")

    qn = 0
    for p in (by_type.get("npn") or []) + (by_type.get("pnp") or []):
        rid = str(p.get("id"))
        qn += 1
        c = _pin(pin2net, rid, "C")
        b = _pin(pin2net, rid, "B")
        e = _pin(pin2net, rid, "E")
        model = "Q2N2222" if p.get("type") == "npn" else "Q2N2907"
        lines.append(f"Q{qn} {c} {b} {e} {model}")

    # black-box comments for ICs
    for t in ("ne555", "regulator_7805", "opamp", "opamp_inverting", "atmega328", "esp32"):
        for p in by_type.get(t) or []:
            lines.append(f"* IC {p.get('id')} type={t} (black-box; connect external models as needed)")

    lines += [
        "",
        ".model DMOD D(Is=1e-14 N=1)",
        ".model LEDMOD D(Is=1e-20 N=1.8)",
        ".model Q2N2222 NPN(IS=1e-14 BF=200)",
        ".model Q2N2907 PNP(IS=1e-14 BF=200)",
        ".op",
        ".end",
        "",
    ]
    return "\n".join(lines)


def to_subckt(circuit: dict, name: str = "Circuit") -> str:
    body = to_cir(circuit, title=name)
    # strip .op/.end and wrap
    lines = []
    for ln in body.splitlines():
        s = ln.strip()
        if s.startswith(".op") or s.startswith(".end") or s.startswith(".model"):
            continue
        if s.startswith("*") and "generated" in s:
            continue
        lines.append(ln)
    # collect external pins = pins connected to vcc/gnd or floating? use all unique nets except 0
    pin2net = _build_pin_net_map(circuit)
    nets = sorted({n for n in pin2net.values() if n != "0"})
    ports = " ".join(nets) if nets else "1"
    out = [f".subckt {name} {ports}"]
    out += lines[1:]  # skip title
    out.append(f".ends {name}")
    return "\n".join(out) + "\n"


